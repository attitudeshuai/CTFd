import datetime
import os

from flask import session

from CTFd.cache import clear_user_session
from CTFd.exceptions import UserNotFoundException, UserTokenExpiredException
from CTFd.models import (
    TOKEN_SCOPE_FULL,
    TOKEN_SCOPE_READ_ONLY,
    TOKEN_SCOPES,
    Users,
    UserTokens,
    db,
)
from CTFd.utils import get_app_config
from CTFd.utils.encoding import hexencode
from CTFd.utils.security.csrf import generate_nonce
from CTFd.utils.security.signing import hmac

# HTTP methods that never modify server state (RFC 7231, Section 4.2.1).
# Read-only scoped tokens are always allowed to use these methods.
TOKEN_SAFE_METHODS = frozenset(("GET", "HEAD", "OPTIONS"))

# Attribute used to explicitly classify a view (or flask-restx Resource class)
# as a read-only endpoint even when it uses a non-safe HTTP method, e.g. the
# CSV/backup export endpoint. Endpoints without this marker are treated
# conservatively: non-safe methods are denied to read-only tokens.
READ_SAFE_ENDPOINT_ATTR = "_ctfd_token_read_safe"


def login_user(user):
    session["id"] = user.id
    session["nonce"] = generate_nonce()
    session["hash"] = hmac(user.password)
    session.permanent = True

    # Clear out any currently cached user attributes
    clear_user_session(user_id=user.id)


def update_user(user):
    session["id"] = user.id
    session["hash"] = hmac(user.password)
    session.permanent = True

    # Clear out any currently cached user attributes
    clear_user_session(user_id=user.id)


def logout_user():
    session.clear()


def generate_preset_admin():
    from CTFd.utils.logging import log

    # Check if user already exists
    preset_admin_name = get_app_config("PRESET_ADMIN_NAME")
    preset_admin_email = get_app_config("PRESET_ADMIN_EMAIL")
    preset_admin_password = get_app_config("PRESET_ADMIN_PASSWORD")

    # We should only promote by email as name may not correctly associate
    user = Users.query.filter_by(email=preset_admin_email).first()

    if user is None:
        # Create the preset admin user
        user = Users(
            name=preset_admin_name,
            email=preset_admin_email,
            password=preset_admin_password,
            type="admin",
            verified=True,
        )
        db.session.add(user)
        db.session.commit()
        log(
            "registrations",
            "[{date}] {ip} - preset admin {name} created",
            name=user.name,
        )

    # If there's already a user, promoting it to an admin represents a mild security risk.
    if user.type != "admin":
        return None

    return user


def generate_user_token(user, expiration=None, description=None, scope=None):
    temp_token = True
    while temp_token is not None:
        value = "ctfd_" + hexencode(os.urandom(32))
        temp_token = UserTokens.query.filter_by(value=value).first()

    # A missing scope (including tokens generated by older code) defaults to
    # full access to preserve existing behavior.
    if scope is None:
        scope = TOKEN_SCOPE_FULL
    token = UserTokens(
        user_id=user.id,
        expiration=expiration,
        description=description,
        scope=scope,
        value=value,
    )
    db.session.add(token)
    db.session.commit()
    return token


def lookup_user_token_with_scope(token):
    """
    Resolve an API token value to its owning user and token scope.

    Returns a (user, scope) tuple. The preset admin token configured through
    application config is not a stored token and always resolves to full scope
    (reported as None, which is treated as full scope by callers).

    Raises UserNotFoundException when the token does not exist and
    UserTokenExpiredException when the token has expired.
    """
    preset_admin_token = get_app_config("PRESET_ADMIN_TOKEN")
    if preset_admin_token and token == preset_admin_token:
        preset_admin = generate_preset_admin()
        if preset_admin:
            return preset_admin, None
    token = UserTokens.query.filter_by(value=token).first()
    if token:
        if datetime.datetime.utcnow() >= token.expiration:
            raise UserTokenExpiredException
        # Legacy rows with a missing/unknown scope are treated as full scope.
        scope = token.scope if token.scope in TOKEN_SCOPES else TOKEN_SCOPE_FULL
        return token.user, scope
    else:
        raise UserNotFoundException


def lookup_user_token(token):
    user, _scope = lookup_user_token_with_scope(token)
    return user


def token_scope_allows_request(scope, method, view_func=None):
    """
    Unified read-only scope enforcement.

    Full scope tokens (and any scope that is not read-only, e.g. legacy tokens
    with a missing scope) may use any method. Read-only tokens may only use
    safe HTTP methods unless the endpoint was explicitly classified as a read
    path with the read-safe marker. Unclassified endpoints are handled
    conservatively: non-safe methods are denied.
    """
    if scope != TOKEN_SCOPE_READ_ONLY:
        return True
    if method in TOKEN_SAFE_METHODS:
        return True
    if view_func is not None:
        if getattr(view_func, READ_SAFE_ENDPOINT_ATTR, False):
            return True
        view_class = getattr(view_func, "view_class", None)
        if view_class is not None and getattr(
            view_class, READ_SAFE_ENDPOINT_ATTR, False
        ):
            return True
    return False
